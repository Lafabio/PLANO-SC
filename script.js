            generateDocBtn.addEventListener('click', async function() {
                try {
                    const { Document, Packer, Paragraph, HeadingLevel, TextRun } = window.docx;
                    if (!Document || !Packer || !window.saveAs) {
                        alert('Não foi possível carregar as bibliotecas de exportação (docx/FileSaver).');
                        return;
                    }

                    const readValue = (id) => (document.getElementById(id)?.value || '').trim();
                    const anoAtual = new Date().getFullYear();
                    const titulo = `Planejamento Anual ${anoAtual}`;
                    const toBulletParagraphs = (value) => {
                        if (!value) {
                            return [new Paragraph('Sem conteúdo informado.')];
                        }

                        return value
                            .split('\n')
                            .map((line) => line.trim())
                            .filter(Boolean)
                            .map((line) => new Paragraph({
                                text: line.replace(/^•\s*/, ''),
                                bullet: { level: 0 }
                            }));
                    };

                    const addTrimSection = (trimNum) => {
                        const heading = new Paragraph({
                            text: `${trimNum}º Trimestre`,
                            heading: HeadingLevel.HEADING_2,
                            spacing: { before: 300, after: 120 }
                        });

                        return [
                            heading,
                            new Paragraph({ text: 'Unidades Temáticas', heading: HeadingLevel.HEADING_3 }),
                            ...toBulletParagraphs(readValue(`unidades${trimNum}`)),
                            new Paragraph({ text: 'Habilidades', heading: HeadingLevel.HEADING_3, spacing: { before: 180 } }),
                            ...toBulletParagraphs(readValue(`habilidades${trimNum}`)),
                            new Paragraph({ text: 'Objetos de Conhecimento', heading: HeadingLevel.HEADING_3, spacing: { before: 180 } }),
                            ...toBulletParagraphs(readValue(`objetos${trimNum}`)),
                            new Paragraph({ text: 'Procedimentos Metodológicos', heading: HeadingLevel.HEADING_3, spacing: { before: 180 } }),
                            ...toBulletParagraphs(readValue(`procedimentos${trimNum}`)),
                            new Paragraph({ text: 'Avaliação', heading: HeadingLevel.HEADING_3, spacing: { before: 180 } }),
                            ...toBulletParagraphs(readValue(`avaliacao${trimNum}`))
                        ];
                    };

                    const doc = new Document({
                        sections: [{
                            children: [
                                new Paragraph({
                                    text: titulo,
                                    heading: HeadingLevel.TITLE
                                }),
                                new Paragraph({
                                    children: [
                                        new TextRun({ text: `Escola: ${readValue('escola') || '-'}`, bold: true })
                                    ]
                                }),
                                new Paragraph(`Professor(a): ${readValue('professor') || '-'}`),
                                new Paragraph(`Área do Conhecimento: ${readValue('areaConhecimento') || '-'}`),
                                new Paragraph(`Componente Curricular: ${readValue('componenteCurricular') || '-'}`),
                                new Paragraph(`Etapa de Ensino: ${readValue('etapaCurso') || '-'}`),
                                new Paragraph(`Série/Ano: ${readValue('serieAnoForm') || '-'}`),
                                ...addTrimSection(1),
                                ...addTrimSection(2),
                                ...addTrimSection(3)
                            ]
                        }]
                    });

                    const blob = await Packer.toBlob(doc);
                    const escolaArquivo = (readValue('escola') || 'planejamento')
                        .toLowerCase()
                        .replace(/[^a-z0-9]+/g, '-')
                        .replace(/(^-|-$)/g, '');
                    window.saveAs(blob, `${escolaArquivo || 'planejamento'}-${anoAtual}.docx`);
                } catch (error) {
                    console.error(error);
                    alert('Erro ao gerar o documento. Verifique os dados e tente novamente.');
                }
            });
            
