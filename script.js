            // Aplicar item ao formulário
            function applyToForm(type, content, trimestre = '1') {
                const textareaId = `${type}${trimestre}`;
                const textarea = document.getElementById(textareaId);
                
                if (textarea) {
                    const currentValue = textarea.value;
                    textarea.value = currentValue ? `${currentValue}\n• ${content}` : `• ${content}`;
                    
                    // Mostrar formulário se estiver oculto
                    if (formSection.classList.contains('hidden')) {
                        showFormBtn.click();
                    }
                    
                    // Ir para o trimestre correto
                    document.querySelector(`[data-form-tab="${trimestre}"]`).click();
                }
            }
            
            // Aplicar todos os itens ao formulário
            function applyAllToForm(trimestre = 1) {
                // Aplicar unidades
                selectedItems.unidades.forEach(content => {
                    applyToForm('unidades', content, trimestre);
                });
                
                // Aplicar habilidades
                selectedItems.habilidades.forEach(content => {
                    applyToForm('habilidades', content, trimestre);
                });
                
                // Aplicar objetos
                selectedItems.objetos.forEach(content => {
                    applyToForm('objetos', content, trimestre);
                });
                
                // Aplicar procedimentos
                selectedItems.procedimentos.forEach(content => {
                    applyToForm('procedimentos', content, trimestre);
                });
                
                // Aplicar avaliação
                selectedItems.avaliacao.forEach(content => {
                    applyToForm('avaliacao', content, trimestre);
                });
            }
